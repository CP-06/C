#include <stdio.h>
int main()
{
    printf("Hey I am good\nnice\n"); // '\n' inserts a new line 
    printf("Hey I am good\tnice\n"); // '\t' inserts a tab space 
    printf("Hey I am good \\ nice\n"); // '\\' inserts a backslash
    printf("Hey I am good \'nice\' \n"); // '\'' inserts a single inverted comma
    printf("Hey I am good \"nice\" \n"); // '\"' inserts a ddouble inverted comma
    return 0;
}