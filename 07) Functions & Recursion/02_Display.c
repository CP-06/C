/*
Write a program with four functions :-
1. Good morning function which prints “good morning”.
2. Good afternoon function which prints “good afternoon”.
3. Good evening function which prints “good evening”.
4. Good night function which prints “good night”.
*/

#include <stdio.h>
void good_morning()
{
    printf("Good Morning\n");
}
void good_afternoon()
{
    printf("Good Afternoon\n");
}
void good_evening()
{
    printf("Good Evening\n");
}
void good_night()
{
    printf("Good Night\n");
}
int main()
{
    good_morning();
    good_afternoon();
    good_evening();
    good_night();
    return 0;
}